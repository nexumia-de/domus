// The one source of the page's security headers. build.mjs writes the
// Content-Security-Policy into index.html (meta tag, protects the app on any
// host) and the `_headers` file (real headers, Cloudflare Workers static
// assets, docs/deployment.md). The header adds frame-ancestors, which a
// meta policy cannot carry (docs/development.md, "Content Security Policy").

const directives = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self'",
  "connect-src 'self' https: http://localhost:* http://127.0.0.1:*",
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
];

/** The policy of the meta tag. */
export const metaPolicy = directives.join('; ');

/** The policy of the header: the same, plus the directive only a header can carry. */
export const headerPolicy = [...directives, "frame-ancestors 'none'"].join('; ');

// The app uses none of these browser features (no camera, location, payment,
// wake lock, ...); the file export is a blob link and needs no permission.
const denied = [
  'accelerometer',
  'browsing-topics',
  'camera',
  'display-capture',
  'geolocation',
  'gyroscope',
  'hid',
  'magnetometer',
  'microphone',
  'midi',
  'payment',
  'screen-wake-lock',
  'serial',
  'usb',
];

// `no-cache` means "store, but ask the server before every use": the files
// have fixed names (no content hash), so nothing may be reused unchecked.
// The files without a rule keep Cloudflare's default, `public, max-age=0,
// must-revalidate` with an ETag, which has the same effect.
const noCache = ['/', '/index.html', '/sw.js', '/manifest.webmanifest'];

/** The `_headers` file (syntax: Cloudflare's "Headers" page for static assets). */
export const headersFile = () =>
  [
    '# Generated by packages/app/build.mjs from packages/app/headers.mjs; do not edit.',
    '/*',
    `  Content-Security-Policy: ${headerPolicy}`,
    '  X-Content-Type-Options: nosniff',
    '  Referrer-Policy: no-referrer',
    `  Permissions-Policy: ${denied.map((feature) => `${feature}=()`).join(', ')}`,
    '  Cross-Origin-Opener-Policy: same-origin',
    '',
    ...noCache.flatMap((path) => [path, '  Cache-Control: no-cache', '']),
  ].join('\n');

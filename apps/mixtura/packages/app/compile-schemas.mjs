// Compiles the JSON Schemas of packages/engine/schemas into plain
// validator functions with Ajv standalone, so the shipped bundle needs
// neither `new Function` nor the Ajv compiler (docs/development.md,
// "Content Security Policy"). Generic over the schema files: every
// `<name>.schema.json` becomes `validators.<name>`; a new schema or field
// needs no change here. Output (git-ignored): src/store/schema-validators.generated.mjs.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, '..', 'engine', 'schemas');
const target = join(here, 'src', 'store', 'schema-validators.generated.mjs');

const files = readdirSync(schemaDir)
  .filter((name) => name.endsWith('.schema.json'))
  .sort();
const schemas = files.map((name) => JSON.parse(readFileSync(join(schemaDir, name), 'utf8')));

// Same options as the former run-time compile: every error, strict schemas.
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  schemas,
  code: { source: true, esm: true, optimize: true },
});

const exportName = (file) => `schema_${file.replace('.schema.json', '').replaceAll('-', '_')}`;
const mapping = Object.fromEntries(files.map((file, i) => [exportName(file), schemas[i].$id]));
const code = standaloneCode(ajv, mapping);
const table = files
  .map((file) => `  '${file.replace('.schema.json', '')}': ${exportName(file)},`)
  .join('\n');

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by compile-schemas.mjs from packages/engine/schemas. Do not edit.\n${code}\nexport const validators = {\n${table}\n};\n`,
);
console.log(`compiled ${files.length} schemas into ${target.slice(here.length + 1)}`);

// Writes src/techniques/techniques.generated.ts: one import per file of data/techniques/. One file
// per technique keeps the work of many people free of merge conflicts, and this index is not
// committed. Runs before tests and typecheck (npm scripts of the engine and the app).
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dataDir = fileURLToPath(new URL('../data/techniques/', import.meta.url));
const out = fileURLToPath(new URL('../src/techniques/techniques.generated.ts', import.meta.url));

export const makeTechniques = () => {
  const files = readdirSync(dataDir)
    .filter((f) => f.endsWith('.json'))
    .sort();
  const imports = files.map((f, i) => `import t${i} from '../../data/techniques/${f}';`);
  const list = files.map((_, i) => `  t${i},`);
  writeFileSync(
    out,
    `// Generated by scripts/make-techniques.mjs; do not edit, not committed.\n${imports.join('\n')}\n\n` +
      `/** Every file of data/techniques/, in file name order; shape checked by the tests. */\n` +
      `export const RAW_TECHNIQUES: readonly unknown[] = [${list.length ? `\n${list.join('\n')}\n` : ''}];\n`,
  );
  return files.length;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) makeTechniques();

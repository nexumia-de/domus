// Writes src/classics/classics.generated.ts: one import per dish file of data/classics/<country>/
// (read by the tests only; the app gets its dishes from dist/classics.json, see shippedContent).
// One file per dish keeps the work of many people free of merge conflicts, and this index is not
// committed. Runs before tests, typecheck and build.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dataDir = fileURLToPath(new URL('./data/classics/', import.meta.url));
const out = fileURLToPath(new URL('./src/classics/classics.generated.ts', import.meta.url));

const techniqueDir = fileURLToPath(new URL('../engine/data/techniques/', import.meta.url));
const handlingDir = fileURLToPath(new URL('../engine/data/handling/', import.meta.url));
const substituteDir = fileURLToPath(new URL('../engine/data/substitutes/', import.meta.url));

const classicFiles = () =>
  readdirSync(dataDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .flatMap((dir) =>
      readdirSync(dataDir + dir.name)
        .filter((f) => f.endsWith('.json'))
        .map((f) => `${dir.name}/${f}`),
    )
    .sort();

/** The content of dist/classics.json: every dish (path order), technique and handling rule (file name order). */
/** The content of dist/classics.json: every dish (path order), technique and substitute (file name order). */
export const shippedContent = () => ({
  format: 'culina-classics',
  formatVersion: 1,
  classics: classicFiles().map((f) => JSON.parse(readFileSync(dataDir + f, 'utf8'))),
  techniques: readdirSync(techniqueDir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => JSON.parse(readFileSync(techniqueDir + f, 'utf8'))),
  handling: readdirSync(handlingDir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => JSON.parse(readFileSync(handlingDir + f, 'utf8'))),
  substitutes: readdirSync(substituteDir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => JSON.parse(readFileSync(substituteDir + f, 'utf8'))),
});

export const makeClassics = () => {
  const files = classicFiles();
  const imports = files.map((f, i) => `import c${i} from '../../data/classics/${f}';`);
  const list = files.map((_, i) => `  c${i},`);
  writeFileSync(
    out,
    `// Generated by make-classics.mjs; do not edit, not committed.\n${imports.join('\n')}\n\n` +
      `/** Every file of data/classics/<country>/, in path order; shape checked by the tests. */\n` +
      `export const RAW_CLASSICS: readonly unknown[] = [${list.length ? `\n${list.join('\n')}\n` : ''}];\n`,
  );
  return files.length;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) makeClassics();

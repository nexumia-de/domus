// Precompiles the engine's JSON Schemas into validators (Ajv standalone code), because the
// app's Content Security Policy forbids eval. Writes src/store/validators.generated.js and
// its .d.ts (git-ignored); runs before tests, typecheck and build.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const schemaDir = fileURLToPath(new URL('../engine/schemas/', import.meta.url));
const outDir = fileURLToPath(new URL('./src/store/', import.meta.url));

/** Export name (the export file's collection name) to schema file. */
export const KINDS = {
  ingredients: 'ingredient',
  templates: 'template',
  components: 'component',
  dishes: 'dish',
  stock: 'stock',
  affinities: 'affinity',
  tastings: 'tasting',
  skills: 'skill',
  cooked: 'cooked',
  favourites: 'favourite',
};

/** Validators that check no stored record: the recipe import format (decision ai-prompt-import). */
export const OTHERS = {
  recipeImport: 'recipe-import',
};

export const compileSchemas = () => {
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    strictRequired: false,
    code: { source: true, esm: true },
  });
  const read = (file) => JSON.parse(readFileSync(schemaDir + file, 'utf8'));
  for (const file of readdirSync(schemaDir).filter((f) => f.endsWith('.schema.json'))) {
    ajv.addSchema(read(file));
  }
  const refs = Object.fromEntries(
    Object.entries({ ...KINDS, ...OTHERS }).map(([kind, name]) => [
      kind,
      read(`${name}.schema.json`).$id,
    ]),
  );
  // Ajv's ESM output still calls require() for its two runtime helpers; make them imports.
  const helpers = [];
  const code = standaloneCode(ajv, refs).replace(
    /const (\w+) = require\("([^"]+)"\)\.default;/g,
    (_, name, path) => {
      // These CommonJS helpers set `exports.default`; a default import gives either the
      // function or the exports object, depending on the tool, so accept both.
      helpers.push(
        `import ${name}Module from "${path}.js";`,
        `const ${name} = ${name}Module.default ?? ${name}Module;`,
      );
      return '';
    },
  );
  if (/require\(/.test(code)) throw new Error('unexpected require() in generated validators');
  const js = `${helpers.join('\n')}\n${code}`;
  const dts =
    'export interface ValidationIssue {\n  instancePath: string;\n  schemaPath: string;\n  keyword: string;\n  params: Record<string, unknown>;\n  message?: string;\n}\n' +
    'export interface Validator {\n  (data: unknown): boolean;\n  errors?: ValidationIssue[] | null;\n}\n' +
    Object.keys({ ...KINDS, ...OTHERS })
      .map((n) => `export const ${n}: Validator;\n`)
      .join('');
  writeFileSync(`${outDir}validators.generated.js`, `// Generated by compile-schemas.mjs.\n${js}`);
  writeFileSync(`${outDir}validators.generated.d.ts`, dts);
};

if (process.argv[1] === fileURLToPath(import.meta.url)) compileSchemas();

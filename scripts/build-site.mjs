// `npm run build:site`: builds every app and lays them out under one address
// in ./dist, with one `_headers` file for Cloudflare Workers static assets.
// `--no-build` reuses the apps' dist folders as they are.
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { apps, home } from './site.mjs';

const root = resolve(import.meta.dirname, '..');
const out = join(root, 'dist');

// Headers for folders whose app brings no `_headers` of its own, and for the
// root page. An app's own file wins for its folder; the two never overlap,
// because Cloudflare joins the values of a header that two rules set.
const baseline = [
  "  Content-Security-Policy: frame-ancestors 'none'",
  '  X-Content-Type-Options: nosniff',
  '  Referrer-Policy: no-referrer',
  '  Cross-Origin-Opener-Policy: same-origin',
];
const noCache = ['', 'index.html', 'sw.js', 'manifest.webmanifest'];

/** An app's `_headers` with every path moved into the app's folder. */
export function prefixHeaders(text, folder) {
  return text
    .split('\n')
    .map((line) => (line.startsWith('/') ? `/${folder}${line}` : line))
    .join('\n')
    .trimEnd();
}

/** The rules for a folder without a `_headers` file; `folder` is '' for the root page. */
export function baselineHeaders(folder, files) {
  const base = folder ? `/${folder}/` : '/';
  const all = folder ? [`${base}*`] : files.map((file) => `${base}${file}`);
  return [
    ...all.flatMap((path) => [path, ...baseline, '']),
    ...noCache
      .filter((file) => folder || files.includes(file))
      .flatMap((file) => [`${base}${file}`, '  Cache-Control: no-cache', '']),
  ]
    .join('\n')
    .trimEnd();
}

if (process.argv[1] === import.meta.filename) {
  if (!process.argv.includes('--no-build')) {
    for (const app of apps) {
      execFileSync('npm', ['run', 'build', '-w', app.name], { cwd: root, stdio: 'inherit' });
    }
  }
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out);

  const headers = ['# Generated by scripts/build-site.mjs; do not edit.'];
  for (const file of home.files) cpSync(join(root, home.dir, file), join(out, file));
  headers.push(baselineHeaders('', ['', ...home.files]));

  for (const app of apps) {
    const from = join(root, app.dist);
    if (!existsSync(join(from, 'index.html'))) throw new Error(`${app.dist} has no index.html`);
    const own = join(from, '_headers');
    cpSync(from, join(out, app.name), { recursive: true, filter: (path) => path !== own });
    headers.push(
      existsSync(own)
        ? prefixHeaders(readFileSync(own, 'utf8'), app.name)
        : baselineHeaders(app.name, []),
    );
  }
  writeFileSync(join(out, '_headers'), `${headers.join('\n\n')}\n`);
  console.log(`dist: / and ${apps.map((app) => `/${app.name}/`).join(', ')}`);
}
